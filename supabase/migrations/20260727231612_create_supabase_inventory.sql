create table if not exists public.products (
  sku text primary key,
  name text not null,
  unit text not null default 'vial',
  price_mxn integer not null check (price_mxn >= 0),
  source_price_mxn integer check (source_price_mxn >= 0),
  stock_on_hand integer not null default 0 check (stock_on_hand >= 0),
  low_stock_threshold integer not null default 5 check (low_stock_threshold >= 0),
  active boolean not null default true,
  source text not null default 'airtable-import',
  updated_at timestamptz not null default now()
);

create table if not exists public.inventory_movements (
  id bigint generated by default as identity primary key,
  sku text not null references public.products(sku),
  quantity_delta integer not null check (quantity_delta <> 0),
  movement_type text not null check (movement_type in ('initial_import', 'restock', 'sale', 'refund', 'adjustment')),
  order_id bigint references public.orders(id),
  mp_payment_id text,
  note text,
  created_at timestamptz not null default now(),
  unique (order_id, sku, movement_type)
);

alter table public.products enable row level security;
alter table public.inventory_movements enable row level security;

revoke all on public.products from anon, authenticated;
revoke all on public.inventory_movements from anon, authenticated;
grant all on public.products to service_role;
grant all on public.inventory_movements to service_role;

alter table public.orders add column if not exists external_reference text;
create unique index if not exists orders_external_reference_key
  on public.orders (external_reference)
  where external_reference is not null;

